#!/usr/bin/env python3
"""Generate named Python calldata builders from the pinned client-facing ABI inventory."""
import argparse,json,re,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
rows=json.loads((ROOT/'crates/exchanges/polymarket/schema/contracts.json').read_text())
def snake(n):return re.sub(r'([a-z0-9])([A-Z])',r'\1_\2',n).lower()
out=['# Generated by scripts/generate-polymarket-contracts.py.','from . import _native']
for interface in dict.fromkeys(r['interface']for r in rows):
 out.append('class '+interface+':')
 for r in rows:
  if r['interface']!=interface:continue
  signature=r['signature'];name=signature.split('(')[0].split()[-1];start=signature.index('(');depth=1;i=start+1;parameters=[];field=''
  while depth:
   ch=signature[i];i+=1
   if ch=='(':depth+=1
   elif ch==')':depth-=1
   if depth==0:
    if field.strip():parameters.append(field.strip())
   elif ch==','and depth==1:parameters.append(field.strip());field=''
   else:field+=ch
  names=[]
  for index,param in enumerate(parameters):
   parts=param.rsplit(' ',1);names.append(parts[-1]if len(parts)>1 and re.fullmatch('[A-Za-z_][A-Za-z0-9_]*',parts[-1])else'arg_'+str(index))
  mapping=', '.join(repr(k)+': '+k for k in names)
  # Positional values also cover unnamed inputs (e.g. multisend's bytes).
  vals='['+', '.join(names)+']'
  out.extend(['    @staticmethod',f'    def {snake(name)}('+', '.join(names)+') -> str:',f'        return _native.polymarket_encode_call({interface!r}, {name!r}, {vals})'])
text='\n'.join(out)+'\n';path=ROOT/'crates/python/python/aux_py/_polymarket_contracts.py'
if a.check:
 if path.read_text()!=text:raise SystemExit('stale Polymarket contract builders')
else:path.write_text(text)

# The same signature inventory owns the typed Rust callable interfaces.
rust='//! Client-facing contract interfaces pinned to the official unified SDK.\nuse alloy_sol_types::sol;\n'
for interface in dict.fromkeys(r['interface']for r in rows):
 rust+='sol! {\n interface '+interface+' {\n'
 for row in rows:
  if row['interface']!=interface:continue
  signature=row['signature']
  if interface=='IProxyFactory':
   rust+='struct Call { uint8 typeCode; address to; uint256 value; bytes data; }\n';signature=signature.replace('(uint8 typeCode, address to, uint256 value, bytes data)[]','Call[]')
  rust+='  '+signature+';\n'
 rust+=' }\n}\n'
rust=subprocess.run(['rustfmt','--edition','2024','--emit','stdout'],input=rust,text=True,capture_output=True,check=True).stdout
path=ROOT/'crates/exchanges/polymarket/src/contracts.rs'
if a.check:
 if path.read_text()!=rust:raise SystemExit('stale Polymarket Rust contract interfaces')
else:path.write_text(rust)
