def zig_type(ty):
    ty = ty.strip()
    primitives = {
        "String": "[]const u8",
        "serde_json::Value": "std.json.Value",
        "serde_json::Number": "model.Number",
        "NativeNumber": "model.NativeNumber",
    }
    if ty in primitives:
        return primitives[ty]
    for prefix, wrapper in [
        ("Box<", "*const {}"),
        ("Vec<", "[]const {}"),
        ("Option<", "?{}"),
        ("std::collections::BTreeMap<String,", "std.json.ArrayHashMap({})"),
        ("serde_json::Map<String,", "std.json.ArrayHashMap({})"),
    ]:
        if ty.startswith(prefix):
            return wrapper.format(zig_type(ty[len(prefix) : -1]))
    if ty.startswith("["):
        inner, length = ty[1:-1].split(";")
        return "[" + length.strip() + "]" + zig_type(inner)
    if ty.startswith("("):
        return (
            "struct { "
            + ", ".join(zig_type(t.strip()) for t in ty[1:-1].split(","))
            + " }"
        )
    if not re.fullmatch(r"\w+", ty):
        raise ValueError(ty)
    return ty


def default(ty, schema):
    if ty.startswith("Option<"):
        return "null"
    if ty.startswith("Vec<"):
        return "&.{}"
    if ty == "String":
        return '""'
    if ty == "bool":
        return "false"
    if ty == "NativeNumber":
        return ".{ .number = .{} }"
    if ty == "serde_json::Number" or ty.startswith("std::collections"):
        return ".{}"
    if ty in schema["aliases"]:
        return default(schema["aliases"][ty], schema)
    if ty in schema["models"]:
        fields = [
            f'.@"{k}" = ' + default(t, schema)
            for k, _, t, m in schema["models"][ty]
            if m in ("required", "present")
        ]
        return ".{" + ", ".join(fields) + "}"
    if re.fullmatch("[iu][0-9]+", ty):
        return "0"
    raise ValueError(ty)


def generate(emit, groups, models_for):
    out = ROOT / "sdk/zig"
    (out / "generated").mkdir(exist_ok=True)
    workflows(emit)
    sessions(emit)
    api = ["// Generated by tools/zig_bindings.py."]
    for (client, venue), methods in sorted(
        {**groups, ("DatabentoLiveClient", "databento"): []}.items()
    ):
        slug = models_for.get(client)
        schema = SCHEMAS.get(slug, {})
        unit = slug or (
            "databento_live" if client == "DatabentoLiveClient" else "tardis_machine"
        )
        api.extend(
            [
                f'pub const {unit} = @import("generated/{unit}.zig");',
                f"pub const {client} = {unit}.Client;",
            ]
        )
        lines = [
            "// Generated by tools/zig_bindings.py.",
            "// zig fmt: off",
            'const rt = @import("../runtime.zig");',
            'const std = @import("std");',
            'const model = @import("../model.zig");',
        ]
        for name, variants in schema.get("enums", {}).items():
            lines.append(
                "pub const "
                + name
                + " = enum { "
                + ", ".join("@" + json.dumps(k) for k, _ in variants)
                + " };"
            )
        for name, variants in schema.get("unions", {}).items():
            lines.extend(
                [
                    "pub const " + name + " = union(enum) {",
                    *[f"    {k}: {zig_type(t)}," for k, t in variants],
                    "    pub const jsonStringify = model.Untagged(@This()).write;",
                    "    pub const jsonParseFromValue = model.Untagged(@This()).read;",
                    "};",
                ]
            )
        for n, t in schema.get("aliases", {}).items():
            lines.append(f"pub const {n} = {zig_type(t)};")
        for name, fields in schema.get("models", {}).items():
            lines.append(f"pub const {name} = struct {{")
            for k, _, t, m in fields:
                init = (
                    " = " + default(t, schema)
                    if m not in ("required", "present")
                    else ""
                )
                lines.append(f"    @{json.dumps(k)}: {zig_type(t)}{init},")
            opened = name not in schema.get("strict", [])
            if opened:
                lines.append("    extra: std.json.ObjectMap = .empty,")
            modes = ", ".join("." + m for _, _, _, m in fields)
            lines.extend(
                [
                    f"    const codec = model.Codec(@This(), &.{{{modes}}}, {str(opened).lower()});",
                    "    pub const jsonStringify = codec.write;",
                    "    pub const jsonParseFromValue = codec.read;",
                    "};",
                ]
            )
        lines.append("pub const routes = .{")
        for name, op in sorted(methods):
            arg, result = map(zig_type, schema["methods"][name])
            lines.append(f'    .{{ "{op}", "{name}", {arg}, {result} }},')
        lines.append("};")
        lines += [
            "pub const Client = struct {",
            "    runtime: rt.Client,",
            "    pub fn init(allocator: std.mem.Allocator, options: rt.Options) Client {",
            "        return .{ .runtime = .{ .allocator = allocator, .options = options } };",
            "    }",
        ]
        for name, op in sorted(methods):
            arg, result = map(zig_type, schema["methods"][name])
            lines.extend(
                [
                    f'    pub fn @"{name}"(self: Client, params: {arg}) !rt.Owned({result}) {{',
                    f'        return self.runtime.request({result}, "{venue}", "{op}", params);',
                    "    }",
                ]
            )
        for op in STREAMS.get(client, "").split():
            actual = (
                "kalshi_perps"
                if client == "KalshiPerpsClient" and op == "open_rpc"
                else "polymarket_perps"
                if client == "PolymarketPerpsClient"
                else venue
            )
            lines.extend(
                [
                    f"    pub fn {op}(self: Client, params: anytype) !rt.Stream {{",
                    f'        return self.runtime.open("{actual}", "{op}", params);',
                    "    }",
                ]
            )
        lines.extend(client_helpers(client))
        lines.append("};")
        emit(out / "generated" / f"{unit}.zig", "\n".join(lines) + "\n")
    emit(out / "clients.zig", "\n".join(api) + "\n")


def workflows(emit):
    """Use the same dispatch inventories as the native protocol implementations."""
    out = ROOT / "sdk/zig"
    header = [
        "// Generated by tools/zig_bindings.py.",
        "// zig fmt: off",
        'const rt = @import("runtime.zig");',
    ]
    lines = header + ['const chain = @import("chain.zig");']
    sources = {
        "metric_helper": [
            "exchanges/metric/" + m for m in ("math", "oracle", "planning", "workflows")
        ],
        "polymarket_helper": ["exchanges/polymarket/chain"],
        "phoenix_transaction": ["exchanges/phoenix/transaction"],
        "evm_reader": ["core/rpc"],
        "evm_chain": ["core/evm_chain"],
        "solana_chain": ["exchanges/pascal/solana_rpc"],
        "phoenix_chain": ["exchanges/phoenix/rpc"],
        "extended_onboarding": ["exchanges/extended/onboarding"],
        "paradex_onboarding": ["exchanges/paradex/onboarding"],
        "metric_chain": ["exchanges/metric/chain"],
        "signer": ["core/signer"],
    }
    for group, paths in sources.items():
        methods = []
        for path in paths:
            src = (ROOT / "src" / (path + ".zig")).read_text()
            match = re.search(
                r"(?:const Op = enum|std\.meta\.stringToEnum\(enum)\s*\{([^}]+)\}", src
            )
            methods += [
                k.strip()
                for k in match[1].split(",")
                if k.strip() and k.strip() != "new"
            ]
        lines.append(f"pub const {group} = struct {{")
        for method in methods:
            recv, call = (
                "rt.Client",
                f'client.invoke(.{group}, .{{ .operation = "{method}", .params = rt.paramsObject(params), .auth = client.options.auth, .origin = client.options.origin }})',
            )
            if group in ("evm_reader", "evm_chain", "metric_chain"):
                action = {
                    "evm_reader": "read",
                    "evm_chain": "transaction",
                    "metric_chain": "metric",
                }[group]
                recv, call = "chain.Evm", f'client.{action}("{method}", params)'
            if group in ("solana_chain", "phoenix_chain"):
                recv, call = "chain.Solana", f'client.command("{method}", params)'
            if group == "signer":
                call = f'client.withFields(.signer, "{method}", params)'
            lines.extend(
                [
                    f'    pub fn @"{method}"(client: {recv}, params: anytype) !rt.Owned(rt.Value) {{',
                    f"        return {call};",
                    "    }",
                ]
            )
        lines.append("};")
    lines.append("pub const instructions = struct {")
    for name in sorted(
        json.loads((ROOT / "tests/phoenix-instructions.json").read_text())
    ):
        lines.extend(
            [
                f"    pub fn {name}(client: rt.Client, request: anytype) !rt.Owned(rt.Value) {{",
                f'        return phoenix_transaction.build_instruction(client, .{{ .name = "{name}", .request = request }});',
                "    }",
            ]
        )
    lines.append("};")
    emit(out / "workflows.zig", "\n".join(lines) + "\n")

    lines = header + ['const chain = @import("chain.zig");']
    contracts = {}
    for line in (
        (ROOT / "src/exchanges/metric/schema/metric-contract-methods.tsv")
        .read_text()
        .splitlines()
    ):
        contract, signature, name, _, mode = line.split("\t")
        contracts.setdefault(contract, []).append((signature, name, mode))
    for contract, methods in contracts.items():
        lines.extend(
            [
                f"pub const {contract} = struct {{",
                "    contract: chain.Contract,",
                f"    pub fn init(client: chain.Evm, address: []const u8) {contract} {{",
                f'        return .{{ .contract = .{{ .chain = client, .venue = .metric, .name = "{contract}", .address = address }} }};',
                "    }",
            ]
        )
        for signature, name, mode in methods:
            arg, action = (
                ("options: chain.ReadOptions", "call")
                if mode == "call"
                else ("value: []const u8", "prepare")
            )
            lines.extend(
                [
                    f'    pub fn @"{name}"(self: {contract}, args: anytype, {arg}) !rt.Owned(rt.Value) {{',
                    f'        return self.contract.{action}("{signature}", args, {arg.split(":")[0]});',
                    "    }",
                ]
            )
        lines.append("};")
    emit(out / "contracts.zig", "\n".join(lines) + "\n")


def sessions(emit):
    # All wire commands go through the same owned, cancellable stream handle.
    lines = [
        "// Generated by tools/zig_bindings.py.",
        "// zig fmt: off",
        'const rt = @import("runtime.zig");',
    ]
    shared = session_commands(ROOT)
    rpc = {
        "derive": shared["Derive"],
        "polymarket_perps": shared["PolymarketPerps"],
        "polymarket_rfq": shared["PolymarketRfq"],
        "kalshi": [
            "subscribe",
            "unsubscribe",
            "list_subscriptions",
            "update_subscription",
        ],
        "paradex": [
            "subscribe_channel",
            "unsubscribe_channel",
            "modify_subscription",
            "create_order",
            "create_batch",
            "modify_order",
            "cancel_order",
            "cancel_by_client_id",
            "cancel_all",
            "cancel_batch",
            "set_cancel_on_disconnect",
        ],
        "pascal": ["place_orders", "cancel_orders", "mass_cancel", "ping"],
        "qfex": ["add_order", "cancel_order", "user_orders", "subscribe_account"],
    }
    for group, methods in rpc.items():
        lines.append(f"pub const {group} = struct {{")
        if group != "qfex":
            methods = [*methods, "pending", "reconcile"]
        for name in dict.fromkeys(methods):
            empty = name in ("pending", "reconcile", "ping", "subscribe_account")
            params = "" if empty else ", params: anytype"
            expr = (
                f'stream.command(.{{ .operation = "{name}" }})'
                if empty
                else f'stream.rpc("{name}", params)'
            )
            lines.extend(
                [
                    f"    pub fn {name}(stream: *const rt.Stream{params}) !rt.Owned(rt.Value) {{",
                    f"        return {expr};",
                    "    }",
                ]
            )
        lines.append("};")
    for group, methods in {
        "databento": {
            "subscribe": "subscription",
            "unsubscribe": "subscription",
            "start_session": "",
            "session_id": "",
            "metadata": "",
            "read_batch": "limit",
        },
        "hyperdash": {
            "subscribe": "subscription",
            "ack": "sub batch",
            "unsubscribe": "sub",
        },
        "tardis": {"send": "message", "read_batch": "limit"},
    }.items():
        lines.append(f"pub const {group} = struct {{")
        for name, fields in methods.items():
            signature = "".join(f", {f}: anytype" for f in fields.split())
            args = "".join(f", .{f} = {f}" for f in fields.split())
            lines.extend(
                [
                    f"    pub fn {name}(stream: *const rt.Stream{signature}) !rt.Owned(rt.Value) {{",
                    f'        return stream.command(.{{ .operation = "{name}"{args} }});',
                    "    }",
                ]
            )
        lines.append("};")
    emit(ROOT / "sdk/zig/sessions.zig", "\n".join(lines) + "\n")


def client_helpers(label):
    methods = []

    def method(name, args, expr, ret="rt.Owned(rt.Value)"):
        methods.extend(
            [
                f"    pub fn {name}(self: Client{', ' + args if args else ''}) !{ret} {{",
                f"        return {expr};",
                "    }",
            ]
        )

    def subscribe(name, fields, args):
        method(
            "subscribe_" + name,
            args,
            "self.subscribe(.{ " + fields + " })",
            "rt.Stream",
        )

    if label == "LighterClient":
        for op in (
            "auth_token",
            "create_order",
            "cancel_order",
            "resync_nonce",
            "prepare_transaction",
        ):
            method(
                op,
                "params: anytype",
                f'self.runtime.request(rt.Value, "lighter", "{op}", params)',
            )
        for op, channel, field in [
            ("order_book", "order_book", "market_id"),
            ("trades", "trade", "market_id"),
            ("account", "account_all", "account_index"),
            ("account_orders", "account_all_orders", None),
        ]:
            subscribe(
                op,
                f'.channel = "{channel}"' + (f", .{field} = {field}" if field else ""),
                f"{field}: u64" if field else "",
            )
    elif label == "HyperliquidClient":
        for op, kind, field, extra in [
            ("l2_book", "l2Book", "coin", None),
            ("trades", "trades", "coin", None),
            ("order_updates", "orderUpdates", "user", None),
            ("user_fills", "userFills", "user", "aggregateByTime"),
            ("clearinghouse_state", "clearinghouseState", "user", "dex"),
            ("open_orders", "openOrders", "user", "dex"),
        ]:
            args = f"{field}: []const u8"
            fields = f'.type = "{kind}", .{field} = {field}'
            if extra:
                fields += f", .{extra} = option"
                args += ", option: " + (
                    "?bool" if extra == "aggregateByTime" else "?[]const u8"
                )
            subscribe(op, fields, args)
        method(
            "sign_user_action",
            "action: rt.Value, chain_id: u64",
            '@import("../identity.zig").hyperliquidAction(self.runtime, action, chain_id)',
        )
    elif label == "ChainlinkDataStreamsClient":
        method(
            "decode_report",
            "bytes: []const u8",
            "self.runtime.invokeBytes(rt.Value, .chainlink_decode_report, bytes)",
        )
        method(
            "subscribe_reports",
            "params: anytype",
            "self.subscribe(params)",
            "rt.Stream",
        )
    elif label == "MonacoClient":
        method(
            "login",
            'options: anytype, wallet: @import("../signing.zig").Signer',
            '@import("../identity.zig").MonacoSession.login(self.runtime, options, wallet)',
            '@import("../identity.zig").MonacoSession',
        )
        method(
            "restore_session",
            "options: anytype, info: rt.Value",
            '@import("../identity.zig").MonacoSession.restore(self.runtime, options, info)',
            '@import("../identity.zig").MonacoSession',
        )
    elif label == "DeriveClient":
        for name, args, fields in [
            ("sign_action", "action: anytype", ".action = action"),
            (
                "prepare_signed",
                "request: anytype, module_data: anytype",
                ".request = request, .module_data = module_data",
            ),
        ]:
            method(
                name,
                args,
                "self.runtime.invoke(.derive_offline_action, .{ .api_key = self.runtime.options.api_key, .api_secret = self.runtime.options.api_secret, .origin = self.runtime.options.origin, .chain_id = self.runtime.options.chain_id, "
                + fields
                + " })",
            )
    elif label == "PhoenixClient":
        method(
            "build_instruction",
            "name: []const u8, request: anytype",
            '@import("../workflows.zig").phoenix_transaction.build_instruction(self.runtime, .{ .name = name, .request = request })',
        )
        for name in (
            "prepare_transaction",
            "assemble_transaction",
            "validate_server_transaction",
            "validate_signed_transaction",
            "sign_transaction",
        ):
            method(
                name,
                "params: anytype",
                f'@import("../workflows.zig").phoenix_transaction.{name}(self.runtime, params)',
            )
    elif label == "PascalClient":
        method(
            "wallet_outcome_pending",
            "",
            "self.runtime.invoke(.pascal_wallet_pending, .{ .auth = self.runtime.options.auth })",
        )
        method(
            "reconcile_wallet",
            "",
            "self.runtime.invoke(.pascal_reconcile_wallet, self.runtime.options.auth orelse return error.AuthenticationRequired)",
        )
        method(
            "sign_permit_at",
            "operation: []const u8, body: anytype, timestamp: u64",
            '@import("../identity.zig").pascalPermitAt(self.runtime, operation, body, timestamp)',
        )
    elif label == "ExtendedClient":
        for name, native in [
            ("settlement", "extended_settlement"),
            ("prepare_order", "extended_order"),
            ("sign_order", "extended_order"),
        ]:
            method(name, "request: anytype", f"self.runtime.invoke(.{native}, request)")
    elif label == "ParadexClient":
        method(
            "authenticate",
            "",
            '@import("../identity.zig").paradexAuthenticate(self.runtime)',
        )
        method(
            "sign_typed_data",
            "data: anytype",
            "self.runtime.invoke(.paradex_sign_typed, .{ .auth = self.runtime.options.auth, .typed_data = data })",
        )
    elif label == "ArcusClient":
        method(
            "signing_payload",
            "operation: []const u8, params: anytype",
            "self.runtime.invoke(.arcus_signing_payload, .{ .operation = operation, .params = params, .auth = self.runtime.options.auth })",
        )
    elif label == "TardisMachineClient":
        for name in ("replay", "replay_normalized"):
            method(
                name,
                "options: anytype",
                f"self.machine_{name}(.{{ .options = options }})",
                "rt.Stream",
            )
    elif label == "QfexClient":
        for op in ("add_order", "cancel_order", "user_orders", "subscribe_account"):
            ret = "rt.Stream" if op == "subscribe_account" else "rt.Owned(rt.Value)"
            args = "" if op == "subscribe_account" else ", request: anytype"
            methods.extend(
                [
                    f"    pub fn {op}(self: Client{args}) !{ret} {{",
                    "        var stream = try self.trading_session(.{});",
                ]
            )
            if args:
                methods.extend(
                    [
                        "        defer stream.deinit();",
                        f'        return stream.rpc("{op}", request);',
                    ]
                )
            else:
                methods.extend(
                    [
                        "        errdefer stream.deinit();",
                        '        var reply = try stream.command(.{ .operation = "subscribe_account" });',
                        "        reply.deinit();",
                        "        return stream;",
                    ]
                )
            methods.append("    }")
    return methods
