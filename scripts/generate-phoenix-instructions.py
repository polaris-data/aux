#!/usr/bin/env python3
"""Generate language-neutral dispatch from the pinned, vendored Rise builders."""
import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / 'crates/exchanges/phoenix'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
# Restricted risk-authority liquidation and onboarder administration are outside
# the published client-facing scope. All remaining public instruction builders
# are available through the same Rust-owned dispatch in every language.
excluded = {'create_liquidate_native_sol_ix', 'create_liquidate_spot_ix', 'create_set_onboarder_signer_ix'}
lines = ['#![allow(deprecated)]', '// Generated by scripts/generate-phoenix-instructions.py.',
         'use crate::{Error, instructions};', 'use serde_json::Value;',
         'fn pubkey(value: Value) -> Result<solana_pubkey::Pubkey, Error> {',
         'value.as_str().ok_or(Error::InvalidRequest("expected base58 public key"))?.parse().map_err(|_| Error::InvalidRequest("invalid public key"))', '}',
         'pub fn build_instruction(name: &str, request: Value) -> Result<Value, Error> {', 'let value = match name {']
rows = []
for path in sorted((BASE / 'src/instructions').rglob('*.rs')):
    module = 'instructions::flight' if path.parent.name == 'flight' else '::'.join(path.relative_to(BASE / 'src').with_suffix('').parts)
    if path.name == 'mod.rs':
        continue
    for match in re.finditer(r'pub fn (create_\w+)\s*\((.*?)\)\s*->\s*([^\{]+)\{', path.read_text(), re.S):
        name, arguments, result = match.groups()
        if name in excluded or 'Instruction' not in result:
            continue
        parameters = [tuple(p.strip().split(': ', 1)) for p in arguments.strip().strip(',').split(',') if p.strip()]
        unary = len(parameters) == 1
        expressions = []
        for key, typ in parameters:
            value = 'request' if unary else f'request.get("{key}").cloned().ok_or(Error::InvalidRequest("missing {key}"))?'
            expression = f'pubkey({value})?' if typ == 'Pubkey' else f'serde_json::from_value({value})?'
            expressions.append('&' + expression if typ.startswith('&') else expression)
        call = f'{module}::{name}(' + ','.join(expressions) + ')'
        if result.strip().startswith('Result'):
            call += '.map_err(|_| Error::InvalidRequest("invalid instruction parameters"))?'
        lines.append(f'{json.dumps(name)} => serde_json::to_value({call})?,')
        rows.append({'method': name, 'rust': module + '::' + name,
                     'params': module + '::' + parameters[0][1] if unary else '{' + ', '.join(k + ': ' + v for k, v in parameters) + '}',
                     'python': 'PhoenixClient.build_instruction', 'node': 'PhoenixClient.buildInstruction',
                     'fixture': 'tests/fixtures/instruction_dispatch.json#' + name,
                     'test_file': 'tests/instruction_dispatch.rs', 'test': 'every_instruction_dispatch_fixture'})
lines += ['_ => return Err(Error::InvalidRequest("unsupported native instruction builder")),', '}; Ok(value)', '}']
rendered = subprocess.run(['rustfmt', '--edition', '2024', '--emit', 'stdout'], input='\n'.join(lines)+'\n', text=True, check=True, capture_output=True).stdout
file = BASE / 'src/tools.rs'
coverage = BASE / 'coverage.json'
manifest = json.loads(coverage.read_text())
manifest['instruction_builders'] = rows
outputs = {file: rendered, coverage: json.dumps(manifest, indent=2)+'\n'}
for file, output in outputs.items():
    if args.check:
        assert file.read_text() == output, f'stale generated file: {file.relative_to(ROOT)}'
    else:
        file.write_text(output)
print(f'Phoenix: {len(rows)} native instruction builders')
