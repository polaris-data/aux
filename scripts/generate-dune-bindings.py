#!/usr/bin/env python3
"""Generate Dune operations and thin Python/Node bindings from the owned inventory.

Offline and deterministic; all HTTP, authentication and decoding stays in Rust.
"""
import argparse
import importlib.util
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / 'crates/data/dune'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
CHECK = parser.parse_args().check
operations = json.loads((BASE / 'operations.json').read_text())
spec = importlib.util.spec_from_file_location('node_codegen', ROOT / 'scripts/node-codegen.py')
node = importlib.util.module_from_spec(spec)
spec.loader.exec_module(node)


def write(file, content):
    if file.suffix == '.rs':
        content = subprocess.run(['rustfmt', '--edition', '2024', '--emit', 'stdout'], input=content, text=True, capture_output=True, check=True).stdout
    if CHECK:
        if not file.exists() or file.read_text() != content:
            raise SystemExit(f'Generated file is stale: {file.relative_to(ROOT)}')
    else:
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(content)


rust = ['//! Generated by scripts/generate-dune-bindings.py. Do not edit.', 'use crate::*;', 'use crate::client::{query_path, execution_path};', 'use aux_rs_core::StreamingHttpTransport;', 'impl<T: StreamingHttpTransport> DuneClient<T> {']
py = ['// Generated by scripts/generate-dune-bindings.py. Do not edit.', 'use super::*;', '#[pymethods]', 'impl DuneClient {']
wrapper = ['"""Generated Dune API wrappers. Protocol behavior remains in Rust."""', 'from __future__ import annotations', 'from typing import Any', 'from . import _native', 'from ._data import _DataClient', '', 'class DuneClient(_DataClient):', '    """Dune execution/results APIs; every method performs one request."""', '', '    def __init__(self, api_key: str, *, api_url: str = "https://api.dune.com/api/v1",', '                 timeout_ms: int = 10_000) -> None:', '        self._inner = _native.DuneClient(api_key, api_url=api_url, timeout_ms=timeout_ms)', '']
stubs = ['# BEGIN GENERATED DUNE', 'class DuneClient:', '    def __init__(self, api_key: str, *, api_url: str = "https://api.dune.com/api/v1", timeout_ms: int = 10_000) -> None: ...', '    @property', '    def closed(self) -> bool: ...', '    async def aclose(self) -> None: ...']


def method(name, args, result='PyResult<Bound<\'py, PyAny>>', asynchronous=True, getter=False, defaults=None):
    return dict(name=name, args=args, **{'return': result, 'async': asynchronous, 'getter': getter, 'static': False, 'constructor': name == 'new', 'defaults': defaults or {}, 'resource': '()' if name == 'aclose' else None})


methods = [method('new', [['api_key', 'String'], ['api_url', '&str'], ['timeout_ms', 'u64']], 'PyResult<Self>', False, defaults={'api_url': '"https://api.dune.com/api/v1"', 'timeout_ms': '10000'}), method('closed', [], 'bool', False, True), method('aclose', [], 'PyResult<()>')]
coverage = []
for op in operations:
    name, argument, request = op['method'], op['argument'], op['request']
    rust_args, call_args, binding_args, signature, public_args, invoke_args = [], [], [], [], [], []
    if argument:
        is_query = argument == 'query_id'
        rust_args.append(f'{argument}: ' + ('u64' if is_query else '&str'))
        call_args.append(argument if is_query else '&' + argument)
        binding_args.append([argument, 'u64' if is_query else 'String'])
        signature.append(argument)
        public_args.append(f'{argument}: ' + ('int' if is_query else 'str'))
        invoke_args.append(argument)
        tail = op['path'].split('}/', 1)[1]
        path = f'&format!("{{}}/{tail}", {"query_path" if is_query else "execution_path"}({argument})?)'
    else:
        path = '"' + op['path'] + '"'
    if request:
        rust_args.append(f'request: {request}')
        call_args.append('request')
        binding_args.append(['request', "Option<Bound<'py, PyAny>>" if op['request_optional'] else "Bound<'py, PyAny>"])
        signature.append('request=None' if op['request_optional'] else 'request')
        public_args.append('request: dict[str, Any] | None = None' if op['request_optional'] else 'request: dict[str, Any]')
        invoke_args.append('request')
    rust.append(f'pub async fn {name}(&self, {", ".join(rust_args)}) -> Result<{op["response"]}> {{')
    if name == 'execute_sql':
        rust.append('if request.sql.trim().is_empty() { return Err(Error::InvalidRequest("sql must be nonempty")); }')
    if op['handler'] == 'post':
        body = 'Some(request)' if request else 'None::<()>'
        rust.append(f'self.post({path}, {body}).await')
    else:
        rust.append(f'self.{op["handler"]}({path}, '+('request' if request else 'ResultOptions::default()')+').await')
    rust.append('}')
    if signature:
        py.append('#[pyo3(signature=(' + ', '.join(signature) + '))]')
    args = ', '.join(f'{key}: {typ}' for key, typ in binding_args)
    py.append(f"fn {name}<'py>(&self, py: Python<'py>" + (', ' + args if args else '') + ") -> PyResult<Bound<'py, PyAny>> {")
    if request:
        py.append(f'let request: v::{request} = input(' + ('request' if op['request_optional'] else 'Some(request)') + ')?;')
    py += ['let client = self.state.client()?;', 'self.state.run(py, async move {', f'client.{name}({", ".join(call_args)}).await.map_err(native)', '})', '}']
    wrapper += ['    async def ' + name + '(self, ' + ', '.join(public_args) + ') -> dict[str, Any]:', '        return await self._inner.' + name + '(' + ', '.join(invoke_args) + ')', '']
    stubs.append('    async def ' + name + '(self, ' + ', '.join(public_args) + ') -> dict[str, Any]: ...')
    methods.append(method(name, binding_args, defaults={'request': 'None'} if op['request_optional'] else {}))
    coverage.append(dict(id=name, method=name, protocol=op['verb'], address='/v1/' + op['path'], response=op['response'], rust='DuneClient::'+name, python='DuneClient.'+name, node='DuneClient.'+re.sub(r'_([a-z])', lambda m: m[1].upper(), name), fixture='tests/fixtures/http.json#'+name, test='tests/contracts.rs#native_http_inventory', python_test='test_dune_http_inventory_and_precision', node_test='Dune HTTP inventory and precision'))
rust.append('}')
py.append('}')
write(BASE / 'src/operations.rs', '\n'.join(rust) + '\n')
source = '\n'.join(py) + '\n'
write(ROOT / 'crates/python/src/dune/operations.rs', source)
write(ROOT / 'crates/node/src/dune/operations.rs', node.operations(source))
write(ROOT / 'crates/python/python/aux_py/_dune.py', '\n'.join(wrapper))
stubs.append('# END GENERATED DUNE')
file = ROOT / 'crates/python/python/aux_py/_native.pyi'
text = file.read_text()
block = '\n'.join(stubs) + '\n'
pattern = r'# BEGIN GENERATED DUNE\n.*?# END GENERATED DUNE\n'
text = re.sub(pattern, lambda _: block, text, flags=re.S) if re.search(pattern, text, re.S) else text.rstrip() + '\n\n' + block
write(file, text)
schemas = {}
for op, row in zip(operations, coverage):
    for name in filter(None, (op['request'], op['response'])):
        schemas.setdefault(name, dict(row, name=name))
write(BASE / 'coverage.json', json.dumps(dict(operations=coverage, schemas=list(schemas.values())), indent=2) + '\n')
file = ROOT / 'crates/node/src/api.json'
api = json.loads(file.read_text())
api['classes']['DuneClient'] = dict(module='dune', methods=methods)
write(file, json.dumps(api, indent=2) + '\n')
file = BASE / 'src/models.rs'
spec = importlib.util.spec_from_file_location('typescript_models', ROOT / 'scripts/typescript-models.py')
renderer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(renderer)
write(file, renderer.annotate(file.read_text()))
file = ROOT / 'crates/node/src/models.json'
models = json.loads(file.read_text())
models['dune'] = {name: 'aux_rs::dune::' + name for name in re.findall(r'pub (?:struct|enum) (\w+)', (BASE / 'src/models.rs').read_text())}
write(file, json.dumps(models, indent=2) + '\n')
print(f'Dune: {len(operations)} operations generated for Rust, Python and Node')
