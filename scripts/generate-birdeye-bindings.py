#!/usr/bin/env python3
"""Generate Birdeye's owned Rust/Python/Node market-data contracts offline.

The pinned operation inventory contains the selected official OpenAPI parameters.
No native binaries, network access, or external Dune/Birdeye SDKs are required.
"""
import argparse
import importlib.util
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / 'crates/data/birdeye'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
CHECK = parser.parse_args().check
OPS = json.loads((BASE / 'operations.json').read_text())
assert len(OPS) == 46 and len({op['method'] for op in OPS}) == 46


def module(name, filename):
    spec = importlib.util.spec_from_file_location(name, ROOT / 'scripts' / filename)
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result


node = module('node_codegen', 'node-codegen.py')
ts = module('typescript_models', 'typescript-models.py')


def write(file, content):
    if file.suffix == '.rs':
        content = subprocess.run(['rustfmt', '--edition', '2024', '--emit', 'stdout'], input=content, text=True, capture_output=True, check=True).stdout
    if CHECK:
        if not file.exists() or file.read_text() != content:
            raise SystemExit(f'Generated file is stale: {file.relative_to(ROOT)}')
    else:
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(content)


def pascal(name):
    return ''.join(part.title() for part in name.split('_'))


def camel(name):
    return re.sub(r'_([a-z])', lambda m: m[1].upper(), name)


def rust_type(schema):
    typ = schema.get('type')
    if typ == 'array':
        return 'Vec<' + rust_type(schema.get('items', {})) + '>'
    return {'string': 'String', 'boolean': 'bool', 'integer': 'i64', 'number': 'serde_json::Number'}.get(typ, 'serde_json::Value')


def ts_type(typ):
    if typ.startswith('Option<'):
        inner = typ[7:-1]
        value = ts_type(inner)
        return ('(' + value + ')' if 'serde_json::' in inner else value) + ' | null'
    if typ.startswith('Vec<'):
        return 'Array<' + ts_type(typ[4:-1]) + '>'
    return {'String': 'string', 'bool': 'boolean', 'i64': 'bigint', 'serde_json::Number': 'number | bigint | string', 'serde_json::Value': 'LosslessValue'}.get(typ, typ)


models = ['//! Generated by scripts/generate-birdeye-bindings.py. Do not edit.', 'use serde::{Deserialize, Serialize};']
declarations = {}
model_names = []


def model(name, fields):
    model_names.append(name)
    models.extend(['#[derive(Clone, Debug, Default, Deserialize, Serialize)]', '#[serde(deny_unknown_fields)]', f'pub struct {name} {{'])
    properties = []
    for field in fields:
        native_name = field['name']
        rust_name = 'r#type' if native_name == 'type' else native_name
        typ = field.get('rust_type') or rust_type(field['schema'])
        if not field['required']:
            typ = f'Option<{typ}>'
            models.append('#[serde(default, skip_serializing_if = "Option::is_none")]')
        models.append(f'pub {rust_name}: {typ},')
        properties.append(f'{native_name}{"?" if not field["required"] else ""}: {ts_type(typ)},')
    models.append('}')
    declarations[name] = f'export type {name} = {{ ' + ' '.join(properties) + ' };'


rust = ['//! Generated by scripts/generate-birdeye-bindings.py. Do not edit.', 'use crate::*;', 'use aux_rs_core::{HttpMethod, StreamingHttpTransport};', 'impl<T: StreamingHttpTransport> BirdeyeClient<T> {']
py = ['// Generated by scripts/generate-birdeye-bindings.py. Do not edit.', 'use super::*;', '#[pymethods]', 'impl BirdeyeClient {']
wrapper = ['"""Generated Birdeye wrappers. Protocol and exact values are handled by Rust."""', 'from __future__ import annotations', 'from typing import Any', 'from . import _native', 'from ._data import _DataClient', '', 'class BirdeyeClient(_DataClient):', '    def __init__(self, api_key: str, *, chain: str = "solana",', '                 api_url: str = "https://public-api.birdeye.so", timeout_ms: int = 10_000) -> None:', '        self._inner = _native.BirdeyeClient(api_key, chain=chain, api_url=api_url, timeout_ms=timeout_ms)', '']
stubs = ['# BEGIN GENERATED BIRDEYE', 'class BirdeyeClient:', '    def __init__(self, api_key: str, *, chain: str = "solana", api_url: str = "https://public-api.birdeye.so", timeout_ms: int = 10_000) -> None: ...', '    @property', '    def closed(self) -> bool: ...', '    async def aclose(self) -> None: ...']


def method(name, args, result="PyResult<Bound<'py, PyAny>>", asynchronous=True, getter=False, defaults=None):
    return dict(name=name, args=args, **{'return': result, 'async': asynchronous, 'getter': getter, 'static': False, 'constructor': name == 'new', 'defaults': defaults or {}, 'resource': '()' if name == 'aclose' else None})


methods = [method('new', [['api_key', 'String'], ['api_url', '&str'], ['timeout_ms', 'u64'], ['chain', 'String']], 'PyResult<Self>', False, defaults={'api_url': '"https://public-api.birdeye.so"', 'timeout_ms': '10000', 'chain': '"solana"'}), method('closed', [], 'bool', False, True), method('aclose', [], 'PyResult<()>')]
coverage, schemas, dispatch = [], [], ['// Generated typed fixture dispatch. Assertions live in contracts.rs.', 'async fn invoke(client: &BirdeyeClient<Mock>, name: &str, request: &str) -> Result<ApiResponse> {', 'match name {']
for op in OPS:
    name = op['method']
    request = pascal(name) + 'Request'
    fields = list(op['fields'])
    if op['body'] is not None:
        body = pascal(name) + 'Body'
        schema = op['body']
        model(body, [dict(name=k, schema=v, required=k in schema.get('required', [])) for k, v in schema.get('properties', {}).items()])
        fields.append(dict(name='body', rust_type=body, required=True))
    model(request, fields)
    optional = not any(field['required'] for field in fields)
    rust.extend([f'pub async fn {name}(&self, request: {request}) -> Result<ApiResponse> {{', f'self.request(HttpMethod::{op["verb"].title()}, "{op["path"].lstrip("/")}", request).await', '}'])
    py.extend(['#[pyo3(signature=(request=None))]' if optional else '#[pyo3(signature=(request))]', f"fn {name}<'py>(&self, py: Python<'py>, request: " + ("Option<Bound<'py, PyAny>>" if optional else "Bound<'py, PyAny>") + ") -> PyResult<Bound<'py, PyAny>> {", f'let request: v::{request} = input(' + ('request' if optional else 'Some(request)') + ')?;', 'let client = self.state.client()?;', f'self.state.run(py, async move {{ client.{name}(request).await.map_err(native) }})', '}'])
    public = 'request: dict[str, Any] | None = None' if optional else 'request: dict[str, Any]'
    wrapper.extend([f'    async def {name}(self, {public}) -> dict[str, Any]:', f'        return await self._inner.{name}(request)', ''])
    stubs.append(f'    async def {name}(self, {public}) -> dict[str, Any]: ...')
    methods.append(method(name, [['request', "Option<Bound<'py, PyAny>>" if optional else "Bound<'py, PyAny>"]], defaults={'request': 'None'} if optional else {}))
    row = dict(id=name, method=name, protocol=op['verb'], address=op['path'], response='ApiResponse', rust='BirdeyeClient::'+name, python='BirdeyeClient.'+name, node='BirdeyeClient.'+camel(name), fixture='tests/fixtures/http.json#'+name, test='tests/contracts.rs#native_http_inventory', python_test='test_birdeye_http_inventory_and_precision', node_test='Birdeye HTTP inventory and precision')
    coverage.append(row)
    schemas.append(dict(row, name=request))
    if op['body'] is not None:
        schemas.append(dict(row, name=body))
    dispatch.append(f'"{name}" => client.{name}(serde_json::from_str(request).unwrap()).await,')
rust.append('}')
py.append('}')
dispatch.extend(['_ => panic!("uncovered Birdeye operation {name}"),', '}', '}'])
models.extend(['/// Native envelope with exact JSON data, including null and version/chain-specific fields.', '#[derive(Clone, Debug, Deserialize, Serialize)]', 'pub struct ApiResponse {', 'pub success: bool,', 'pub data: serde_json::Value,', '#[serde(flatten)]', 'pub extra: serde_json::Map<String, serde_json::Value>,', '}'])
model_names.append('ApiResponse')
schemas.append(dict(coverage[0], name='ApiResponse'))
declarations['ApiResponse'] = 'export type ApiResponse = { success: boolean, data: LosslessValue, } & { [key: string]: LosslessValue };'
raw_models = subprocess.run(['rustfmt', '--edition', '2024', '--emit', 'stdout'], input='\n'.join(models)+'\n', text=True, capture_output=True, check=True).stdout
write(BASE/'src/models.rs', ts.annotate(raw_models))
write(BASE/'src/operations.rs', '\n'.join(rust)+'\n')
write(BASE/'tests/generated/dispatch.rs', '\n'.join(dispatch)+'\n')
write(ROOT/'crates/python/src/birdeye/operations.rs', '\n'.join(py)+'\n')
write(ROOT/'crates/node/src/birdeye/operations.rs', node.operations('\n'.join(py)+'\n'))
write(ROOT/'crates/python/python/aux_py/_birdeye.py', '\n'.join(wrapper))
stubs.append('# END GENERATED BIRDEYE')
file=ROOT/'crates/python/python/aux_py/_native.pyi'
pattern=r'# BEGIN GENERATED BIRDEYE\n.*?# END GENERATED BIRDEYE\n'
block='\n'.join(stubs)+'\n'
source=file.read_text()
source=re.sub(pattern,lambda _:block,source,flags=re.S) if re.search(pattern,source,re.S) else source.rstrip()+'\n\n'+block
write(file, source)
write(BASE/'coverage.json', json.dumps(dict(operations=coverage,schemas=schemas),indent=2)+'\n')
file=ROOT/'crates/node/src/api.json'
api=json.loads(file.read_text());api['classes']['BirdeyeClient']=dict(module='birdeye',methods=methods)
write(file,json.dumps(api,indent=2)+'\n')
file=ROOT/'crates/node/src/models.json'
models=json.loads(file.read_text());models['birdeye']={name:'aux_rs::birdeye::'+name for name in model_names}
write(file,json.dumps(models,indent=2)+'\n')
# This small primitive-field subset mirrors the Rust ts-rs declarations without a build.
write(BASE/'typescript.json',json.dumps(declarations,indent=2)+'\n')
rows=['# Birdeye endpoint coverage','', '46 market-data REST endpoints; other Birdeye API groups are excluded.', '', '| Group | HTTP endpoint | Rust / Python | TypeScript |','| --- | --- | --- | --- |']
for op in OPS:
    rows.append(f'| {op["group"]} | `{op["verb"]} {op["path"]}` | `{op["method"]}` | `{camel(op["method"])}` |')
write(BASE/'COVERAGE.md','\n'.join(rows)+'\n')
print('Birdeye: 46 Rust/Python/Node operations and typed requests generated without native builds')
