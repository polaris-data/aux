def camel(name):
    return re.sub(r'_([a-z])',lambda m:m[1].upper(),name)

def resource(method):
    if method.get('resource'):return method['resource']
    ret=method['return'].removeprefix('PyResult<').removesuffix('>')
    return ret if ret in CLASSES else None

def ref_type(t):
    m=re.search(r"PyRef<'_,\s*(\w+)>",t)
    return m[1] if m else None

def adapter(cls,d,m):
    name=m['name'];ctor=name=='new';getter=m['getter'];static=m['static'];res=resource(m)
    args=[] if getter else ['args: String'];values=[];setup=[]
    for key,t in m['args']:
        ref=ref_type(t)
        if ref:
            optional=t.startswith('Option<');args.append(f'{key}: '+(f'Option<&Node{ref}>' if optional else f'&Node{ref}'))
            values.append(f'{key}.map(|s| &s.inner)' if optional else f'&{key}.inner');continue
        if key=='callback':
            args.append("callback: Function<'_, String, Promise<String>>")
            setup.append('let callback = std::sync::Arc::new(callback.build_threadsafe_function().callee_handled::<false>().weak::<true>().build().map_err(|_| crate::errors::SigningError::new_err("unable to register signer callback"))?);');values.append('callback');continue
        if 'Bound<' in t:
            if t.startswith('Option<'):values.append(f'args.get("{key}").filter(|v| !v.is_null())'+('' if '&Bound' in t else '.cloned()'))
            elif t.startswith('&'):values.append(f'args.get("{key}").unwrap_or(&serde_json::Value::Null)')
            else:values.append(f'convert::arg(&args, "{key}")?')
        elif t=='&str':
            setup.append(f'let {key}: String = convert::arg(&args,"{key}")?;');values.append(f'&{key}')
        elif t=='Option<&str>':
            setup.append(f'let {key}: Option<String> = convert::arg(&args,"{key}")?;');values.append(f'{key}.as_deref()')
        else:values.append(f'convert::arg(&args,"{key}")?')
    params=(', '.join(([] if ctor or static else ['&self'])+args))
    ret='Self' if ctor or static else ('Node'+res if res and res!='()' else 'String')
    attr='constructor' if ctor else ('factory' if static else ('getter' if getter else ''))
    pubname='close' if name=='aclose' else name
    lines=[f'#[napi({attr})]' if attr else '#[napi]',f'pub {"async " if m["async"] else ""}fn {pubname}({params}) -> napi::Result<{ret}> {{']
    if not getter:lines+=['let args = convert::input(&args).map_err(Error::into_napi)?; let _ = &args;']
    lines+=['let call = || -> crate::prelude::Result<_> {' if not m['async'] else 'let result = async {']
    lines+=setup
    path=f'{d["module"].split("::")[0]}::{cls}::{name}' if ctor or static else f'self.inner.{name}'
    call=f'{path}('+', '.join(values)+')'+('.await' if m['async'] else '')
    if m['return'].startswith('PyResult'):call+='?'
    unit = res=='()' or m['return'] in ('PyResult<()>','()')
    lines+=[f'{call};' if unit else f'let value = {call};']
    if ctor or static:lines+=['Ok(Self { inner: value })']
    elif res and res!='()':lines += [f'Ok(Node{res} {{ inner: value }})']
    else:lines+=['convert::encode(())' if unit else ('convert::encode(serde_value::Value::Bytes(value))' if 'PyBytes' in m['return'] else 'convert::encode(value)')]
    lines+=['}.await;' if m['async'] else '}; let result = call();','result.map_err(Error::into_napi)','}']
    return '\n'.join(lines)

