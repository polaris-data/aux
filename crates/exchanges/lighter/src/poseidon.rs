use poseidon_hash::Goldilocks as F;

pub(crate) fn hash(elements: &[u64]) -> [u8; 40] {
    let mut state = [F::zero(); 12];
    // Overwrite sponge: preserve unused rate lanes in a partial block.
    for block in elements.chunks(8) {
        for (slot, value) in state.iter_mut().zip(block) {
            *slot = F::from_canonical_u64(*value);
        }
        permute(&mut state);
    }
    let mut bytes = [0; 40];
    for (slot, element) in bytes.chunks_exact_mut(8).zip(&state[..5]) {
        slot.copy_from_slice(&element.to_canonical_u64().to_le_bytes());
    }
    bytes
}
fn sbox(x: F) -> F {
    let x2 = x.mul(&x);
    let x3 = x2.mul(&x);
    x3.mul(&x3).mul(&x)
}
fn external(s: &mut [F; 12]) {
    for block in s.chunks_exact_mut(4) {
        let [a, b, c, d] = [block[0], block[1], block[2], block[3]];
        let ab = a.add(&b);
        let cd = c.add(&d);
        let sum = ab.add(&cd);
        block[0] = sum.add(&ab).add(&b);
        block[1] = sum.add(&b).add(&c).add(&c);
        block[2] = sum.add(&cd).add(&d);
        block[3] = sum.add(&d).add(&a).add(&a);
    }
    let sums: [F; 4] = std::array::from_fn(|i| s[i].add(&s[i + 4]).add(&s[i + 8]));
    for (i, value) in s.iter_mut().enumerate() {
        *value = value.add(&sums[i % 4]);
    }
}
fn full(s: &mut [F; 12], rounds: std::ops::Range<usize>) {
    for r in rounds {
        for (i, value) in s.iter_mut().enumerate() {
            *value = sbox(value.add(&F(EXTERNAL[r][i])));
        }
        external(s);
    }
}
fn permute(s: &mut [F; 12]) {
    external(s);
    full(s, 0..4);
    for constant in INTERNAL {
        s[0] = sbox(s[0].add(&F(constant)));
        let sum = s.iter().fold(F::zero(), |sum, v| sum.add(v));
        for (i, v) in s.iter_mut().enumerate() {
            *v = sum.add(&v.mul(&F(DIAGONAL[i])));
        }
    }
    full(s, 4..8);
}
