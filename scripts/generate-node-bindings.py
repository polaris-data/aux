def ts_type(t,venue):
    t=t.strip()
    if t.startswith('Option<'):return ts_type(t[7:-1],venue)+' | null'
    if t.startswith('Vec<'):return 'Array<'+ts_type(t[4:-1],venue)+'>'
    if t.startswith('Box<'):return ts_type(t[4:-1],venue)
    generic=re.fullmatch(r'([\w:]+)<(.+)>',t)
    if generic and generic[1].rsplit('::',1)[-1] in MODELS.get(venue,{}):return venue+'.'+generic[1].rsplit('::',1)[-1]+'<'+ts_type(generic[2],venue)+'>'
    if t.startswith('BTreeMap<') or t.startswith('std::collections::BTreeMap<'):return 'Record<string, LosslessValue>'
    if 'PyRef<' in t:return ref_type(t)
    if 'Bound<' in t or t in ('serde_json::Value','Value'):return 'LosslessValue'
    if t in ('String','&str',"&'static str"):return 'string'
    if t=='bool':return 'boolean'
    if t in ('u64','i64','u128','i128','usize','isize'):return 'bigint'
    if t in ('u8','u16','u32','i8','i16','i32','f32','f64'):return 'number'
    if t in ('()','Self'):return 'void'
    name=t.rsplit('::',1)[-1]
    if name in CLASSES:return name
    if name in MODELS.get(venue,{}):return venue+'.'+name
    if venue=='metric' and name in ('U256','I256','B256','Bytes','Address','Signature'):return 'string'
    if t.startswith('['):return 'Array<LosslessValue>'
    return 'LosslessValue'

def model_arg(cls,d,m,key,typ):
    venue=VENUE[d['module'].split('::')[0]]
    if cls.startswith('Lighter'):venue='lighter'
    if key=='callback':
        callbacks={
            'HyperliquidSigner':('{digest: number[]; network: string; scheme: string}', 'hyperliquid.Signature'),
            'LighterSigner':('{digest: number[]; chainId: number | bigint; accountIndex: number | bigint; apiKeyIndex: number; purpose: {type: string; tx_type?: number; nonce?: number | bigint; deadline?: number | bigint}}', 'string'),
            'DeriveSigner':('{digest: string; chain_id: number | bigint; scheme: string}', 'string'),
            'ExtendedSigner':('{digest: string; scheme: string; typed_data: LosslessValue; personal_message: string | null}', 'string | string[]'),
            'PhoenixSigner':('{message_base64: string; public_key: string; scheme: string}', 'string'),
            'ParadexSigner':('{digest: string; scheme: string; typed_data: LosslessValue; personal_message: string | null}', 'string | string[]'),
            'MonacoSessionSigner':('number[]','string'), 'MonacoWalletSigner':('string','string'),
            'MetricSigner':('{digest: string; address: string; scheme: string}','string'),
        }
        payload,result=callbacks[cls]
        return '(payload: '+payload+') => '+result+' | Promise<'+result+'>'
    if 'Bound<' not in typ:return ts_type(typ,venue)
    # Find the owned Rust adapter's explicit parse type.
    module=d['module'];folder=BASE/'src'/module.replace('::','/')
    files=[folder.with_suffix('.rs')] if folder.with_suffix('.rs').exists() else sorted(folder.glob('*.rs'))
    for p in files:
        text=p.read_text();match=re.search(r'fn '+re.escape(m['name'])+r'\([^\{]*\{',text)
        if not match:continue
        body=text[match.end():text.find('\n    }',match.end())]
        found=re.search(r'let (?:mut )?\w+:\s*([\w:<>, ]+)\s*=\s*(?:convert::parse\(&?'+re.escape(key)+r'\)|input\('+re.escape(key)+r'\))',body)
        if not found:found=re.search(r'let (?:mut )?'+re.escape(key)+r':\s*([\w:<>]+)\s*=',body)
        if found:
            result=ts_type(found[1],venue)
            return 'NativeInput<'+result+'>' if result!='LosslessValue' else result
    return 'LosslessValue'

def method_output(cls,d,m):
    res=resource(m)
    if res:
        if res=='Subscription':
            if cls=='HyperliquidClient' and m['name']=='subscribe_l2_book':return 'Subscription<hyperliquid.L2Book>'
            if cls=='LighterClient':
                payload={'subscribe_order_book':'BookEvent','subscribe_trades':'TradesEvent','subscribe_account':'AccountEvent','subscribe_account_orders':'AccountOrdersEvent'}.get(m['name'])
                if payload:return 'Subscription<lighter.'+payload+'>'
            venue=VENUE[d['module'].split('::')[0]]
            if 'Event' in MODELS.get(venue,{}):return 'Subscription<'+venue+'.Event>'
        return 'void' if res=='()' else res
    venue=VENUE[d['module'].split('::')[0]]
    if cls.startswith('Lighter'):venue='lighter'
    hints={
        ('HyperliquidSigner','sign'):'hyperliquid.Signature',('HyperliquidSigner','sign_action'):'hyperliquid.SignedRequest',('HyperliquidSigner','sign_user_action'):'hyperliquid.Signature',
        ('LighterSigner','sign'):'string',('LighterSigner','auth_token'):'string',('LighterClient','auth_token'):'string',('LighterClient','next_nonce'):'lighter.NextNonce',
        ('MonacoSessionSigner','sign'):'string',('MonacoWalletSigner','sign_message'):'string',('MonacoClient','login'):'monaco.SessionInfo',
        ('MetricSigner','sign_digest'):'string',('MetricSigner','sign_personal_digest'):'string',('MetricSigner','sign_transaction'):'metric.SignedTransaction',
        ('DeriveSigner','sign'):'string',('ParadexSigner','sign'):'string[]',('ExtendedSigner','sign'):'string[]',('PhoenixSigner','sign_message'):'string',('PhoenixSigner','sign_transaction'):'Record<string, string>',
    }
    if (cls,m['name']) in hints:return hints[cls,m['name']]
    # Full API inventories record exact native response types.
    if venue in ('derive','paradex','metric','phoenix','extended'):
        coverage=json.loads((ROOT/'crates/exchanges'/venue/'coverage.json').read_text())
        for row in coverage['rest']:
            if row['method']==m['name']:return ts_type(row['response'],venue)
    if m['async'] and cls.endswith(('Client','RpcSession')):
        native_type=RUST_RETURNS.get(venue,{}).get(m['name'])
        if native_type:return ts_type(native_type,venue)
    known={
        ('HyperliquidClient','order'):'hyperliquid.ExchangeResponse<hyperliquid.BatchResponse>',('HyperliquidClient','cancel'):'hyperliquid.ExchangeResponse<hyperliquid.BatchResponse>',('HyperliquidClient','cancel_by_cloid'):'hyperliquid.ExchangeResponse<hyperliquid.BatchResponse>',('HyperliquidClient','meta'):'hyperliquid.Meta',('HyperliquidClient','l2_book'):'hyperliquid.L2Book',
        ('HyperliquidClient','clearinghouse_state'):'hyperliquid.UserState',('HyperliquidClient','open_orders'):'Array<hyperliquid.OpenOrder>',
        ('LighterClient','order_books'):'lighter.OrderBooks',('LighterClient','order_book_orders'):'lighter.OrderBookOrders',
        ('LighterClient','recent_trades'):'lighter.Trades',('LighterClient','account'):'lighter.Accounts',
    }
    if (cls,m['name']) in known:return known[cls,m['name']]
    ret=m['return'].removeprefix('PyResult<').removesuffix('>') if m['return'].startswith('PyResult<') else m['return']
    if m['async'] or 'Py<' in ret:return 'LosslessValue'
    if 'PyBytes' in ret:return 'Uint8Array'
    return ts_type(ret,venue)

