#!/usr/bin/env python3
"""Generate product-specific Python command wrappers and native binding stubs."""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
def write(path,text):
 if a.check:
  if path.read_text()!=text:raise SystemExit('stale generated Python interface: '+str(path))
 else:path.write_text(text)
commands={
'KalshiRpcSession':['subscribe','unsubscribe','list_subscriptions','update_subscription'],
'PascalRpcSession':['place_orders','cancel_orders','mass_cancel','ping'],
'PolymarketPerpsRpcSession':['create_orders','modify_orders','modify_orders_coid','cancel_orders','cancel_orders_coid','cancel_all','auto_cancel','update_leverage','update_leverages','update_margin','subscribe','unsubscribe','ping'],
'PolymarketRfqSession':['quote','cancel_quote','last_look'],
}
text='''# Generated by scripts/generate-prediction-python.py.
from __future__ import annotations
from typing import Any
class _CommandSession:
    def __init__(self, inner: Any):
        self._inner = inner
    @property
    def pending(self):
        return self._inner.pending
    async def reconcile(self):
        return await self._inner.reconcile()
    async def next_event(self):
        return await self._inner.next_event()
    async def aclose(self):
        await self._inner.aclose()
    async def __aenter__(self):
        return self
    async def __aexit__(self, *_):
        await self.aclose()
'''
for cls,methods in commands.items():
 text+='\nclass '+cls+'(_CommandSession):\n'
 for method in methods:
  args=''if method=='ping'else'request';text+=f'    async def {method}(self'+(', '+args if args else'')+'):\n'+f'        return await self._inner.{method}({args})\n'
write(ROOT/'crates/python/python/aux_py/_prediction_rpc.py',text)
stubs=[]
for venue in ['polymarket','kalshi','pascal']:
 rows=json.loads((ROOT/'crates/exchanges'/venue/'coverage.json').read_text())['rest']
 for cls in dict.fromkeys(r['client']for r in rows):
  stubs.extend(['class '+cls+':','    def __init__(self, **configuration: Any) -> None: ...','    @property','    def closed(self) -> bool: ...','    @property','    def authenticated(self) -> bool: ...','    async def aclose(self) -> None: ...','    async def subscribe(self, specification: Mapping[str, Any]) -> Subscription: ...','    async def open_rpc(self) -> Any: ...'])
  stubs.extend(f'    async def {r["method"]}(self, request: Mapping[str, Any] | None = None) -> Any: ...'for r in rows if r['client']==cls);stubs.append('')
for cls,key,identity in [('KalshiSigner','private_key_pem','public_key_pem'),('PolymarketSigner','private_key','address'),('PascalSigner','private_key_hex','public_key')]:
 stubs.extend(['class '+cls+':',f'    def __init__(self, {key}: str) -> None: ...','    @staticmethod',f'    def remote({identity}: str, callback: Callable[[Native], Awaitable[str]]) -> {cls}: ...'])
 if cls!='KalshiSigner':stubs.extend(['    @property',f'    def {identity}(self) -> str: ...'])
 if cls=='PolymarketSigner':stubs.extend(['    async def sign_typed_data(self, payload: Native) -> str: ...','    async def sign_order(self, order: Native, *, system: str = "ctf", negative_risk: bool = False) -> str: ...'])
 if cls=='PascalSigner':stubs.append('    async def sign_request(self, owner: str, deployment_id: int, kind: str, request: Native, *, client_ts_ms: int, recv_window_ms: int = 5000) -> Native: ...')
 stubs.append('')
for cls in ['PolymarketChainClient','PascalChainClient']:
 stubs.extend(['class '+cls+':','    def __init__(self, **configuration: Any) -> None: ...','    @property','    def closed(self) -> bool: ...','    async def aclose(self) -> None: ...'])
 source=(ROOT/'crates/python/src'/('polymarket'if cls.startswith('Polymarket')else'pascal')/'chain.rs').read_text();methods=re.findall(r'\n    fn (\w+)',source)
 for method in dict.fromkeys(methods):
  if method not in ['new','closed','aclose','__repr__','transport','drop']:
   if cls=='PascalChainClient' and method=='pending':stubs.extend(['    @property','    def pending(self) -> list[str]: ...'])
   else:stubs.append(f'    '+('async 'if re.search(r'fn '+method+r"<'py>",source)else'')+f'def {method}(self, *args: Any, **kwargs: Any) -> Any: ...')
 stubs.append('')
native_commands={k:v for k,v in commands.items()if not k.startswith('Polymarket')}
native_commands['PolymarketRpcSession']=list(dict.fromkeys(commands['PolymarketPerpsRpcSession']+commands['PolymarketRfqSession']))
for cls,methods in native_commands.items():
 stubs.extend(['class '+cls+':','    @property','    def pending(self) -> Any: ...','    async def reconcile(self) -> Any: ...','    async def next_event(self) -> Any: ...','    async def aclose(self) -> None: ...'])
 for method in methods:stubs.append(f'    async def {method}(self, request: Any = None) -> Any: ...')
 stubs.append('')
stubs+=['def polymarket_encode_call(contract: str, function: str, args: Any) -> str: ...','def polymarket_helper(operation: str, payload: Any) -> Any: ...']
path=ROOT/'crates/python/python/aux_py/_native.pyi'
old=path.read_text();marker='# BEGIN PREDICTION CONNECTORS'
perpetual_marker='# Phoenix and Extended native declarations.'
suffix=perpetual_marker+old.split(perpetual_marker,1)[1] if perpetual_marker in old else ''
old=old.split(marker)[0].rstrip()+'\n\n'
write(path,old+marker+'\n'+'\n'.join(stubs)+'\n'+('\n'+suffix if suffix else ''))
