#!/usr/bin/env python3
"""Record or check production dependency inventories for supported profiles."""

import argparse
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
BASELINE = ROOT / "DEPENDENCIES.md"
TARGET = "aarch64-apple-darwin"
PROFILES = [
    ("Core contracts", "aux-rs-core", ""),
    ("Hyperliquid with custom transports", "aux-rs", "hyperliquid"),
    ("Hyperliquid with standard HTTP", "aux-rs", "hyperliquid,http"),
    ("Hyperliquid with standard WebSockets", "aux-rs", "hyperliquid,ws"),
    ("Hyperliquid with both standard transports", "aux-rs", "hyperliquid,http,ws"),
    ("Lighter with custom transports", "aux-rs", "lighter"),
    ("Lighter with standard HTTP", "aux-rs", "lighter,http"),
    ("Lighter with standard WebSockets", "aux-rs", "lighter,ws"),
    ("Lighter with both standard transports", "aux-rs", "lighter,http,ws"),
    ("Both exchanges with custom transports", "aux-rs", "hyperliquid,lighter"),
    ("Both exchanges with both standard transports", "aux-rs", "hyperliquid,lighter,http,ws"),
    ("Python binding (separate opt-in crate)", "aux-rs-python", ""),
]


def inventory(package, features, target, depth=None):
    command = [
        "cargo", "tree", "--locked", "--package", package,
        "--no-default-features", "--target", target,
        "--edges", "normal,build", "--prefix", "none", "--format", "{p}",
    ]
    if features:
        command += ["--features", features]
    if depth is not None:
        command += ["--depth", str(depth)]
    output = subprocess.check_output(command, cwd=ROOT, text=True)
    # Strip workspace paths and repeated-node annotations, but keep versions.
    packages = {line.split(" (")[0] for line in output.splitlines() if line.strip()}
    return sorted(p for p in packages if not p.startswith(package + " "))


def render(target):
    sections = [
        "# Production dependency baseline\n",
        "Generated by `python3 scripts/dependencies.py --write`. Check with "
        "`python3 scripts/dependencies.py --check`. Uses the committed lockfile "
        "and excludes development dependencies. Counts include internal workspace "
        "crates and build dependencies.\n",
        f"Target: `{target}`. This is a target-specific inventory, not a count "
        "for every platform. Pass `--target` to inspect a different target.\n",
        "Core contracts have no dependencies. Hyperliquid directly adds core, Serde, "
        "Serde JSON, K256 (secp256k1), SHA3 (Keccak), rmp-serde (MessagePack), "
        "hex (native addresses/signatures), and zeroize (temporary secret buffers). "
        "Standard transports add their selected I/O and "
        "TLS stacks; Reqwest brings transitive Tower and tracing crates, but the "
        "SDK has no direct middleware or tracing dependency. Ring is the selected "
        "TLS crypto provider; Hyperliquid's exchange signer uses K256. Standard HTTP "
        "also selects Tokio for cancellation/backoff timers and httpdate for RFC "
        "9110 Retry-After dates. Core contracts still have zero dependencies.\n",
        "Lighter directly adds core, Serde/Serde JSON, goldilocks-crypto 0.1.2 "
        "(ECgFp5/Schnorr primitives), poseidon-hash 0.1.4 (original Poseidon2), "
        "hex, base64 (native wire signatures), zeroize, getrandom (OS-backed "
        "Schnorr randomness), and futures-util (runtime-independent async nonce "
        "mutex). The two cryptographic primitive versions are pinned and unaudited; "
        "see crates/exchanges/lighter/SIGNING.md for compatibility evidence and review limits. "
        "The Plonky2 transaction permutation is ported with attribution; no existing "
        "exchange client, Go runtime, subprocess, Python runtime, or Alloy umbrella "
        "package is used. Python's profile is listed separately; PyO3 is forbidden "
        "in all Rust-only profiles below. Review feature "
        "activation separately with `cargo tree -e features`.\n",
    ]
    for name, package, features in PROFILES:
        packages = inventory(package, features, target)
        names = {dependency.split()[0] for dependency in packages}
        selected = set(features.split(","))
        if "hyperliquid" in selected and "lighter" not in selected and names & {
            "goldilocks-crypto", "poseidon-hash", "aux-rs-lighter"
        }:
            raise SystemExit(f"Lighter signing leaked into Hyperliquid profile: {name}")
        if "lighter" in selected and "hyperliquid" not in selected and names & {
            "k256", "sha3", "rmp-serde", "aux-rs-hyperliquid"
        }:
            raise SystemExit(f"Hyperliquid signing leaked into Lighter profile: {name}")
        if features in {"lighter", "hyperliquid", "hyperliquid,lighter"} and names & {
            "tokio", "reqwest", "tokio-tungstenite", "rustls"
        }:
            raise SystemExit(f"Standard stack leaked into custom transport profile: {name}")
        if package != "aux-rs-python" and any(
            dependency.split()[0].startswith("pyo3")
            or dependency.split()[0] == "aux-rs-python"
            for dependency in packages
        ):
            raise SystemExit(f"Python dependencies leaked into Rust-only profile: {name}")
        direct = inventory(package, features, target, depth=1)
        sections += [
            f"## {name}\n",
            f"Direct dependencies: {len(direct)}. Total unique dependencies: {len(packages)}.\n",
            "```text\n" + "\n".join(packages or ["(none)"]) + "\n```\n",
        ]
    return "\n".join(sections)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--target", default=TARGET)
    args = parser.parse_args()
    content = render(args.target)
    if args.write:
        BASELINE.write_text(content)
        print(f"Updated {BASELINE.name}")
    elif not BASELINE.exists() or BASELINE.read_text() != content:
        raise SystemExit("Dependency baseline changed; review cargo tree and regenerate with --write.")
    else:
        print("Production dependency baseline matches.")


if __name__ == "__main__":
    main()
