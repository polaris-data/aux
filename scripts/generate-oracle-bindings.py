#!/usr/bin/env python3
"""Generate oracle request types and SDK dispatch from the native operation inventories."""
import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
CHECK = parser.parse_args().check
BANNER = '// Generated by scripts/generate-oracle-bindings.py. Do not edit.'
BIND_RESULT = "PyResult<Bound<'py, PyAny>>"
MODULE = 'oracles'


def write(path, source):
    path = ROOT / path
    if path.suffix == '.rs':
        source = subprocess.run(['rustfmt', '--edition', '2024', '--emit', 'stdout'],
                                input=source, text=True, capture_output=True, check=True).stdout
    if CHECK:
        if not path.exists() or source != path.read_text():
            raise SystemExit(f'Stale generated file: {path.relative_to(ROOT)}')
    else:
        path.write_text(source)


def snake(name):
    return re.sub(r'(?<=[a-z0-9])(?=[A-Z])', '_', name).lower()


def method(name, args=(), result=BIND_RESULT, *, async_=True, getter=False, defaults=None, resource=None, **extra):
    return dict(name=name, args=list(args), **{'return': result, 'async': async_},
                getter=getter, static=False, constructor=name == 'new', defaults=defaults or {},
                resource=resource, **extra)


def ts_type(typ):
    if typ.startswith('Vec<'):
        return ts_type(typ[4:-1]) + '[]'
    return {'String': 'string', 'bool': 'boolean', 'u32': 'number', 'u64': '(number | bigint)', 'serde_json::Value': 'NativeValue'}[typ]


py = [BANNER, 'use super::*;']
node = [BANNER, 'use super::*;']
wrapper = ['"""Generated clients for the native oracle APIs."""', 'from typing import Any',
           'from . import _native, Subscription', 'from ._data import _DataClient', '']
pyi = ['# BEGIN GENERATED ORACLES']
api_path = ROOT / 'crates/node/src/api.json'
api = json.loads(api_path.read_text())
for vendor in ('pyth', 'chainlink'):
    base = f'crates/data/{vendor}'
    operations = json.loads((ROOT / base / 'operations.json').read_text())
    dispatch = [BANNER, 'async fn dispatch(row: &serde_json::Value, transport: FixtureTransport) -> Result<TestOutput> {', 'let request = row["request"].clone();', 'match (row["client"].as_str().unwrap(), row["method"].as_str().unwrap()) {']
    models = [BANNER, 'use serde::{Deserialize, Serialize};']
    rust = [BANNER, 'use crate::*;', 'use aux_rs_core::{StreamingHttpTransport, WebSocketTransport};']
    for cls in dict.fromkeys(op['client'] for op in operations):
        classes = [op for op in operations if op['client'] == cls]
        config = 'PythConfig' if vendor == 'pyth' else 'ChainlinkConfig'
        config_types = ('{ api_url?: string; router_url?: string; hermes_url?: string; ws_urls?: string[]; api_key?: string; publisher_token?: string }'
                        if vendor == 'pyth' else '{ network: "mainnet" | "testnet"; api_url?: string; ws_url?: string; candles_url?: string; api_key?: string; api_secret?: string; token?: string }')
        opt = vendor == 'pyth'
        arg = 'Option<Bound<\'py, PyAny>>' if opt else "Bound<'py, PyAny>"
        methods = [method('new', [('config',arg),('timeout_ms','u64')], 'PyResult<Self>', async_=False,
                          defaults={'timeout_ms':'10000', **({'config':'None'} if opt else {})}, types={'config':config_types,'timeout_ms':'number | bigint'}),
                   method('closed', result='bool', async_=False, getter=True), method('aclose', result='PyResult<()>', resource='()')]
        py += [f'#[pymethods] impl {cls} {{', '#[new]',
               '#[pyo3(signature=(config=None, *, timeout_ms=10000))]' if opt else '#[pyo3(signature=(config, *, timeout_ms=10000))]',
               f"fn new(py: Python<'_>, config: {arg.replace(chr(39)+'py',chr(39)+'_')}, timeout_ms:u64) -> PyResult<Self> {{",
               f'let config: {vendor}::{config} = input({"config" if opt else "Some(config)"})?;',
               f'let client = build(py, move || {vendor}::{cls}::with_config(config, transport_config(timeout_ms)?))?;',
               'Ok(Self { state: ClientState::new(client) }) }',
               '#[getter] fn closed(&self) -> bool { self.state.is_closed() }',
               "fn aclose<'py>(&self, py: Python<'py>) -> PyResult<Bound<'py,PyAny>> { self.state.close(py) }"]
        node_arg = 'Option<Input>' if opt else 'Input'
        node += [f'impl {cls} {{', f'pub(crate) fn new(config:{node_arg},timeout_ms:u64)->Result<Self> {{',
                 f'let config: {vendor}::{config} = input({"config" if opt else "Some(config)"})?;',
                 f'let client = build(move || {vendor}::{cls}::with_config(config, transport_config(timeout_ms)?))?;',
                 'Ok(Self { state: ClientState::new(client) }) }',
                 'pub(crate) fn closed(&self) -> bool { self.state.is_closed() }',
                 'pub(crate) async fn aclose(&self) -> Result<()> { self.state.close().await }']
        ctor = 'config: dict[str, Any] | None = None' if opt else 'config: dict[str, Any]'
        wrapper += [f'class {cls}(_DataClient):', f'    def __init__(self, {ctor}, *, timeout_ms: int = 10_000) -> None:',
                    f'        self._inner = _native.{cls}(config, timeout_ms=timeout_ms)', '']
        pyi += [f'class {cls}:', f'    def __init__(self, {ctor}, *, timeout_ms: int = 10_000) -> None: ...',
                '    @property', '    def closed(self) -> bool: ...', '    async def aclose(self) -> None: ...']
        for op in classes:
            name, kind, fields, req = (op[k] for k in ('method', 'kind', 'fields', 'request'))
            stream = kind in ('sse', 'objects', 'pyth_ws', 'chainlink_ws', 'merkle_ws')
            ws = kind.endswith('_ws')
            authorization = cls == 'ChainlinkCandlestickClient' and name == 'authorize'
            response = 'JsonStream' if stream else 'NativeResponse<AuthorizationResponse>' if authorization else 'NativeResponse'
            optional = not any(f['required'] for f in fields)
            if fields:
                derives = 'Clone, Serialize, Deserialize' + (', Default' if optional else '') + ('' if kind=='form' else ', Debug')
                models += [f'#[derive({derives})]', '#[serde(deny_unknown_fields)]',f'pub struct {req} {{']
                for field in fields:
                    wire, typ, required = (field[k] for k in ('name','type','required'))
                    field_name = 'r#type' if wire=='type' else snake(wire)
                    if wire != field_name.removeprefix('r#'):
                        models.append(f'#[serde(rename = "{wire}")]')
                    if not required:
                        models.append('#[serde(default, skip_serializing_if = "Option::is_none")]')
                        typ = f'Option<{typ}>'
                    models.append(f'pub {field_name}: {typ},')
                models.append('}')
            trait = 'WebSocketTransport' if ws else 'StreamingHttpTransport'
            if not ws and cls=='ChainlinkCandlestickClient':
                trait += ' + Clone'
            bound = ' where T::Stream: \'static' if ws else ''
            rust += [f'impl<T: {trait}> {cls}<T>{bound} {{',
                     f'pub async fn {name}(&self'+(f', request: {req}' if fields else '')+f') -> Result<{response}> {{']
            param = 'request' if fields else 'serde_json::json!({})'
            if ws:
                call = 'self.merkle_native().await' if kind == 'merkle_ws' else 'self.subscribe_native(request).await'
            elif stream:
                call = f'self.stream("{op["path"]}", {param}).await'
            else:
                call = f'self.execute("{op["path"]}", {param}, "{kind}").await'
            if authorization:
                call += '?.decode()'
            rust += [call, '}', '}']
            if not ws:
                args = 'serde_json::from_value(request).unwrap()' if fields else ''
                test_type = 'Stream' if stream else 'Response'
                conversion = '.and_then(test_authorization)' if authorization else f'.map(TestOutput::{test_type})'
                dispatch.append(f'("{cls}", "{name}") => {cls}::with_transport(test_config(), transport)?.{name}({args}).await{conversion},')
            if fields:
                arg = f'Option<Bound<\'py, PyAny>>' if optional else "Bound<'py, PyAny>"
                if optional:
                    py.append('#[pyo3(signature=(request=None))]')
                py_args, node_args = ', request: '+arg, ', request: '+('Option<Input>' if optional else 'Input')
                public_args = ', request: dict[str, Any]' + (' | None = None' if optional else '')
                expression = 'request' if optional else 'Some(request)'
                setup = [f'let request: {vendor}::{req} = input({expression})?;']
                args = [('request',arg)]
                ts = '{ ' + '; '.join(f'{f["name"]}{"" if f["required"] else "?"}: {ts_type(f["type"])}' for f in fields) + ' }'
            else:
                py_args = node_args = public_args = ''
                setup, args, ts = [], [], 'never'
            invocation = f'client.{name}({"request" if fields else ""}).await.map_err(errors::data)'
            out = f'Ok(NativeHandle::Oracle({invocation}?))' if stream else invocation
            runner = 'stream' if stream else 'run'
            py += [f"fn {name}<'py>(&self, py: Python<'py>{py_args}) -> {BIND_RESULT} {{", *setup,
                   'let client = self.state.client()?;', f'self.state.{runner}(py, async move {{ {out} }})', '}']
            node += [f'pub(crate) async fn {name}(&self{node_args}) -> Result<{"Subscription" if stream else "Output"}> {{', *setup,
                     'let client = self.state.client()?;',f'self.state.{runner}(async move {{ {out} }}).await', '}']
            public_result = 'Subscription' if stream else 'dict[str, Any]'
            public_call = f'await self._inner.{name}({"request" if fields else ""})'
            wrapper += [f'    async def {name}(self{public_args}) -> {public_result}:',
                        f'        return {"Subscription("+public_call+")" if stream else public_call}', '']
            pyi.append(f'    async def {name}(self{public_args}) -> {"Any" if stream else public_result}: ...')
            methods.append(method(name,args,resource='Subscription' if stream else None,types={'request':ts},
                                  output=None if stream else 'OracleResponse<{ s: string; d: { access_token: string; expiration: bigint } }>' if authorization else 'OracleResponse', defaults={'request':'None'} if fields and optional else {}))
        if cls == 'ChainlinkDataStreamsClient':
            py += ["fn decode_report(&self, full_report: &str) -> PyResult<Py<PyAny>> {",
                   'let client = self.state.client()?;', 'let result = client.decode_report(full_report).map_err(errors::data)?;',
                   'convert::output(result)', '}']
            node += ['pub(crate) fn decode_report(&self, full_report: &str) -> Result<Output> {',
                     'convert::output(self.state.client()?.decode_report(full_report).map_err(errors::data)?)', '}']
            wrapper += ['    def decode_report(self, full_report: str) -> dict[str, Any]:', '        return self._inner.decode_report(full_report)', '']
            pyi += ['    def decode_report(self, full_report: str) -> dict[str, Any]: ...']
            methods.append(method('decode_report',[('full_report','&str')],'PyResult<Py<PyAny>>',async_=False,output='ChainlinkDecodedReport'))
        py.append('}')
        node.append('}')
        api['classes'][cls] = dict(module=MODULE, methods=methods)
        pyi.append('')
    dispatch += ['_ => panic!("unrecognized fixture: {row}"),', '}', '}']
    write(f'{base}/tests/generated/dispatch.rs', '\n'.join(dispatch)+'\n')
    write(f'{base}/src/models.rs', '\n'.join(models)+'\n')
    write(f'{base}/src/operations.rs', '\n'.join(rust)+'\n')
write('crates/python/src/oracles/operations.rs','\n'.join(py)+'\n')
write('crates/node/src/oracles/operations.rs','\n'.join(node)+'\n')
write('crates/python/python/aux_py/_oracles.py','\n'.join(wrapper).rstrip()+'\n')
write('crates/node/src/api.json',json.dumps(api,indent=2)+'\n')
file = 'crates/python/python/aux_py/_native.pyi'
text = (ROOT/file).read_text()
block = '\n'.join(pyi + ['# END GENERATED ORACLES'])+'\n'
pattern = r'# BEGIN GENERATED ORACLES\n.*?# END GENERATED ORACLES\n'
write(file, re.sub(pattern, lambda _:block, text, flags=re.S) if re.search(pattern,text,re.S) else text.rstrip()+'\n\n'+block)
print('Pyth and Chainlink operations generated for Rust, Python and Node')
